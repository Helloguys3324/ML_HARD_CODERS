masks = {k: np.array([[c == '1' for c in row] for row in v]) for k, v in FONT.items()}


def score_word(Z, starts, inv):
    letters, tot, marg = [], 0.0, 0.0
    for st in starts:
        sc = {}
        for ch, M in masks.items():
            on = Z[0:7, st:st + 5][M]
            off = Z[0:7, st:st + 5][~M]
            d = on.mean() - off.mean()
            sc[ch] = -d if inv else d
        ranked = sorted(sc.items(), key=lambda x: -x[1])
        letters.append(''.join(c for c, _ in ranked[:3]))
        tot += ranked[0][1]
        marg += ranked[0][1] - ranked[1][1]
    return letters, tot, marg



    Z = (A - A.mean()) / (A.std() + 1e-9)
    for lname, starts in layouts.items():
        for inv in (False, True):
            letters, tot, marg = score_word(Z, starts, inv)
            print(f'{sname:8s} {lname} {"inv" if inv else "   "} '
                  f'tot={tot:5.2f} marg={marg:4.2f} ' + ' | '.join(letters))

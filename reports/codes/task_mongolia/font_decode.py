#!/usr/bin/env python
"""Score 5x7-font letter hypotheses on the 9x37 count grid."""
import numpy as np
import pandas as pd

OUT = '/home/kozak/mllm/MML/work/solutions/task_mongolia'
s = pd.read_csv(f'{OUT}/survey_plots_ij.csv')
p = pd.read_csv(f'{OUT}/survey_pred_global.csv')
m = dict(zip(p.image, p['count']))
G = np.zeros((9, 37))
for _, r in s.iterrows():
    G[int(r.j), int(r.i)] = m[r.image]

FONT = {
 'A': ["01110","10001","10001","11111","10001","10001","10001"],
 'B': ["11110","10001","10001","11110","10001","10001","11110"],
 'C': ["01110","10001","10000","10000","10000","10001","01110"],
 'D': ["11110","10001","10001","10001","10001","10001","11110"],
 'E': ["11111","10000","10000","11110","10000","10000","11111"],
 'F': ["11111","10000","10000","11110","10000","10000","10000"],
 'G': ["01110","10001","10000","10111","10001","10001","01111"],
 'H': ["10001","10001","10001","11111","10001","10001","10001"],
 'I': ["01110","00100","00100","00100","00100","00100","01110"],
 'J': ["00111","00010","00010","00010","00010","10010","01100"],
 'K': ["10001","10010","10100","11000","10100","10010","10001"],
 'L': ["10000","10000","10000","10000","10000","10000","11111"],
 'M': ["10001","11011","10101","10101","10001","10001","10001"],
 'N': ["10001","11001","10101","10011","10001","10001","10001"],
 'O': ["01110","10001","10001","10001","10001","10001","01110"],
 'P': ["11110","10001","10001","11110","10000","10000","10000"],
 'Q': ["01110","10001","10001","10001","10101","10010","01101"],
 'R': ["11110","10001","10001","11110","10100","10010","10001"],
 'S': ["01111","10000","10000","01110","00001","00001","11110"],
 'T': ["11111","00100","00100","00100","00100","00100","00100"],
 'U': ["10001","10001","10001","10001","10001","10001","01110"],
 'V': ["10001","10001","10001","10001","10001","01010","00100"],
 'W': ["10001","10001","10001","10101","10101","11011","10001"],
 'X': ["10001","10001","01010","00100","01010","10001","10001"],
 'Y': ["10001","10001","01010","00100","00100","00100","00100"],
 'Z': ["11111","00001","00010","00100","01000","10000","11111"],
}
masks = {k: np.array([[c == '1' for c in row] for row in v]) for k, v in FONT.items()}


def best_word(Z, starts, top=6, invert=False):
    word = []
    for st in starts:
        scores = {}
        for ch, M in masks.items():
            on = Z[1:8, st:st + 5][M]
            off = Z[1:8, st:st + 5][~M]
            s = on.mean() - off.mean()
            scores[ch] = -s if invert else s
        ranked = sorted(scores.items(), key=lambda x: -x[1])
        word.append(ranked[:top])
    return word


Z = (G - G.mean()) / (G.std() + 1e-9)
# try several layout variants
layouts = {
    '6x spread 1..31': [1, 7, 13, 19, 25, 31],
    '6x tight 0..30 [0,6,..30]': [0, 6, 12, 18, 24, 30],
    '6x 0..31 even': [0, 6, 12, 18, 24, 30],
}
for name, starts in layouts.items():
    for inv in (False, True):
        w = best_word(Z, starts, top=4, invert=inv)
        print(name, 'invert' if inv else 'normal')
        for st, cand in zip(starts, w):
            print('  x=%2d %s' % (st, ' '.join(f'{c}:{v:.2f}' for c, v in cand)))

# also: maybe 5 letters, positions 1,8,15,22,29 (7 spacing)
for starts in ([1, 8, 15, 22, 29], [1, 7, 13, 19, 25], [2, 8, 14, 20, 26]):
    w = best_word(Z, starts, top=4)
    print('layout', starts)
    for st, cand in zip(starts, w):
        print('  x=%2d %s' % (st, ' '.join(f'{c}:{v:.2f}' for c, v in cand)))
